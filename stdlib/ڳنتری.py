#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""ڳنتری — ریاضی (تینوں زبانیں)"""

import math
import random


# ═══════════════════════════════════════════════════════
# بنیادی
# ═══════════════════════════════════════════════════════

def مطلق(عدد) -> float:
    """مطلق قدر |x|"""
    return abs(عدد)


def گول(عدد, جگہ: int = 0) -> float:
    """عدد کو گول کریں"""
    return round(عدد, جگہ)


def زیادہ(الف, ب):
    """زیادہ والا"""
    return max(الف, ب)


def کم(الف, ب):
    """کم والا"""
    return min(الف, ب)


def جمع_کل(فہرست: list):
    """فہرست کا مجموعہ"""
    return sum(فہرست)


# ═══════════════════════════════════════════════════════
# طاقت / جذر
# ═══════════════════════════════════════════════════════

def طاقت(بنیاد, قوت) -> float:
    """x^y"""
    return pow(بنیاد, قوت)


def جذر(عدد) -> float:
    """√x"""
    return math.sqrt(عدد)


def مکعب_جذر(عدد) -> float:
    """∛x"""
    return عدد ** (1 / 3)


# ═══════════════════════════════════════════════════════
# مثلثیات
# ═══════════════════════════════════════════════════════

def سائن(زاویہ: float) -> float:
    """sin(x) — زاویہ radian میں"""
    return math.sin(زاویہ)


def کوسائن(زاویہ: float) -> float:
    """cos(x)"""
    return math.cos(زاویہ)


def ٹینجنٹ(زاویہ: float) -> float:
    """tan(x)"""
    return math.tan(زاویہ)


# ═══════════════════════════════════════════════════════
# لوگارتھم
# ═══════════════════════════════════════════════════════

def لوگ(عدد) -> float:
    """قدرتی لوگارتھم ln(x)"""
    return math.log(عدد)


def لوگ_10(عدد) -> float:
    """log10(x)"""
    return math.log10(عدد)


def لوگ_2(عدد) -> float:
    """log2(x)"""
    return math.log2(عدد)


# ═══════════════════════════════════════════════════════
# مستقل
# ═══════════════════════════════════════════════════════

پائی = math.pi
ای = math.e


# ═══════════════════════════════════════════════════════
# بے ترتیبی
# ═══════════════════════════════════════════════════════

def بے_ترتیب(فہرست: list):
    """فہرست کو بے ترتیب کریں"""
    random.shuffle(فہرست)
    return فہرست


def چنو(فہرست: list):
    """فہرست سے ایک عنصر چنیں"""
    return random.choice(فہرست)


def بے_ترتیب_عدد(کم: int = 0, زیادہ: int = 100) -> int:
    """بے ترتیب عدد"""
    return random.randint(کم, زیادہ)
